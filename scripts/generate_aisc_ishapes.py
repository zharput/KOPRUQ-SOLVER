"""Generates include/kopruq/io/midas/AiscIShapes.hpp -- the AISC rolled I-shape catalog (W, HP, M, S)
used by MidasSectionLibrary.hpp's "AISC10(US)" catalog lookup.

Source: AISC Shapes Database v16.0 (16th ed. Steel Construction Manual), as packaged in the
steelpy 1.1.1 wheel (Apache-2.0; files "steelpy/shape files/{W,HP,M,S}_shapes.csv").
Usage:  python -I scripts/generate_aisc_ishapes.py <steelpy-1.1.1-py3-none-any.whl>
Values are written exactly as tabulated (US customary: in, in^2, in^4); no unit conversion here.
"""
import csv
import io
import sys
import zipfile

SERIES = ["W", "HP", "M", "S"]
COLS = ["area", "d", "bf", "tw", "tf", "Ix", "Iy", "J"]


def main(wheel: str, out: str) -> None:
    z = zipfile.ZipFile(wheel)
    rows = []
    for s in SERIES:
        data = list(csv.reader(io.TextIOWrapper(z.open(f"steelpy/shape files/{s}_shapes.csv"), encoding="utf-8-sig")))
        header = data[0]
        for r in data[1:]:
            if not r or not r[0].strip():
                continue
            name = r[0].strip().upper().replace("_", ".")  # steelpy writes M12.5X12.4 as M12_5X12_4
            vals = [float(r[header.index(c)]) for c in COLS]
            rows.append((name, vals))
    names = [n for n, _ in rows]
    if len(names) != len(set(names)):
        raise SystemExit("duplicate shape names")
    rows.sort(key=lambda x: x[0])
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("#pragma once\n")
        f.write("// GENERATED by scripts/generate_aisc_ishapes.py -- do not edit by hand.\n")
        f.write("// AISC rolled I-shapes (W, HP, M, S): AISC Shapes Database v16.0 (16th ed. Steel Construction\n")
        f.write("// Manual), as packaged in steelpy 1.1.1 (Apache-2.0). US customary units exactly as tabulated:\n")
        f.write("// A [in^2], d, bf, tw, tf [in], Ix, Iy, J [in^4]. Sorted by name for binary search.\n")
        f.write("#include <array>\n#include <string_view>\n\nnamespace kopruq::io::midas::aisc {\n\n")
        f.write("struct IShapeRow { std::string_view name; double A, d, bf, tw, tf, Ix, Iy, J; };\n\n")
        f.write(f"inline constexpr std::array<IShapeRow, {len(rows)}> kIShapes{{{{\n")
        for n, v in rows:
            f.write("  {\"%s\", %s},\n" % (n, ", ".join(repr(x) for x in v)))
        f.write("}};\n\n} // namespace kopruq::io::midas::aisc\n")
    print(f"wrote {len(rows)} shapes to {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "include/kopruq/io/midas/AiscIShapes.hpp")
